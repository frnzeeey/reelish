Map<String, String> _render(List<_Source> sources, Directory root) {
  final lib = sources.where((source) => !source.isTest).toList();
  final tests = sources.where((source) => source.isTest).toList();
  final byPath = {for (final source in sources) source.path: source};
  final importers = <String, List<String>>{};
  for (final source in sources) {
    for (final target in source.imports) {
      importers.putIfAbsent(target, () => []).add(source.path);
    }
  }
  for (final list in importers.values) {
    list.sort();
  }
  return {
    'docs/codebase/class-reference.md': _classReference(lib, sources),
    'docs/codebase/dependency-map.md': _dependencyMap(lib, importers, byPath),
    'docs/codebase/file-reference.md': _fileReference(lib, importers, tests),
    'docs/codebase/function-reference.md': _functionReference(lib),
  };
}

int _compare(String a, String b) {
  final ka = a.replaceAll(RegExp(r'^[_(]+'), '').toLowerCase();
  final kb = b.replaceAll(RegExp(r'^[_(]+'), '').toLowerCase();
  final order = ka.compareTo(kb);
  return order != 0 ? order : a.compareTo(b);
}

String _letter(String name) {
  final key = name.replaceAll(RegExp(r'^[_(]+'), '');
  final first = key.isEmpty ? '#' : key[0].toUpperCase();
  return RegExp('[A-Z]').hasMatch(first) ? first : '#';
}

String _alphabetNav(Iterable<String> letters) {
  final present = letters.toSet();
  return [
    for (final letter in [
      ...List.generate(26, (i) => String.fromCharCode(65 + i)),
      '#',
    ])
      if (present.contains(letter))
        '[$letter](#${letter == '#' ? 'other' : letter.toLowerCase()})',
  ].join(' · ');
}

String _anchorTitle(String letter) => letter == '#' ? 'Other' : letter;

/// A link from docs/codebase/ to a source line.
String _sourceLink(String path, [int? line]) =>
    '[`${path.split('/').last}${line == null ? '' : ':$line'}`]'
    '(../../$path${line == null ? '' : '#L$line'})';

String _fileLink(String path) => '[`$path`](../../$path)';

String _fileAnchor(String path) => path
    .toLowerCase()
    .replaceAll(RegExp(r'[^a-z0-9 _-]'), '')
    .replaceAll(' ', '-');

String _classReference(List<_Source> lib, List<_Source> all) {
  final types = [for (final source in lib) ...source.types]
    ..sort((a, b) => _compare(a.name, b.name));
  // Where each public type is named outside its own file.
  String usedIn(_Type type) {
    if (type.isPrivate) return 'its own file';
    final pattern = RegExp('\\b${RegExp.escape(type.name)}\\b');
    final users = [
      for (final source in all)
        if (source.path != type.source.path && pattern.hasMatch(source.text))
          source.path,
    ];
    final libUsers = users.where((path) => path.startsWith('lib/')).length;
    final testUsers = users.length - libUsers;
    if (users.isEmpty) return 'its own file only';
    return [
      if (libUsers > 0) '$libUsers lib file${libUsers == 1 ? '' : 's'}',
      if (testUsers > 0) '$testUsers test file${testUsers == 1 ? '' : 's'}',
    ].join(', ');
  }

  final buffer = StringBuffer()
    ..writeln('# Class reference')
    ..writeln()
    ..writeln(_generatedNote)
    ..writeln()
    ..writeln(
      'Every class, enum, mixin, extension and typedef in `lib/`, A–Z '
      '(case-insensitive, leading `_` ignored). **Role** is derived from '
      'the declaration (its superclass) and folder. **Named in** counts the '
      'other files that mention the type by name: a measure of how far a '
      'change reaches. **Summary** is the first sentence of the type\'s own '
      'doc comment; a blank one means the type has none.',
    )
    ..writeln()
    ..writeln(
      '${types.length} types: '
      '${types.where((t) => !t.isPrivate).length} public, '
      '${types.where((t) => t.isPrivate).length} private to their file.',
    )
    ..writeln()
    ..writeln(_alphabetNav(types.map((t) => _letter(t.name))))
    ..writeln();
  String? letter;
  for (final type in types) {
    final current = _letter(type.name);
    if (current != letter) {
      letter = current;
      buffer
        ..writeln()
        ..writeln('## ${_anchorTitle(current)}')
        ..writeln()
        ..writeln(
          '| Type | Role | Declared in | Relations | Platform | '
          'Named in | Summary |',
        )
        ..writeln('|---|---|---|---|---|---|---|');
    }
    buffer.writeln(
      '| `${type.name}` | ${_role(type)} | '
      '${_sourceLink(type.source.path, type.line)} | ${_relations(type)} | '
      '${_platform(type.source.path)} | ${usedIn(type)} | ${type.summary} |',
    );
  }
  return buffer.toString();
}

String _functionReference(List<_Source> lib) {
  final functions = [for (final source in lib) ...source.functions]
    ..sort((a, b) {
      final byName = _compare(a.name, b.name);
      if (byName != 0) return byName;
      return _compare(a.owner ?? '', b.owner ?? '');
    });
  final buffer = StringBuffer()
    ..writeln('# Function and method reference')
    ..writeln()
    ..writeln(_generatedNote)
    ..writeln()
    ..writeln(
      'Top-level functions and methods in `lib/`, A–Z by name, then by '
      'declaring type. Included: every public function and method, and '
      'private ones that carry a doc comment (those are the behaviour the '
      'authors chose to explain). Left out: undocumented private helpers, '
      'framework overrides (`build`, `initState`, `dispose`, …) without a '
      'doc comment, constructors, getters and setters. **Signature** is the '
      'declaration as written, collapsed onto one line. **Async** marks '
      'functions that return a `Future` or `Stream` or are declared '
      '`async`. Callers are not listed: names such as `load` are too common '
      'to match reliably; search the code for `.name(` instead.',
    )
    ..writeln()
    ..writeln(
      '${functions.length} entries: '
      '${functions.where((f) => f.owner == null).length} top-level, '
      '${functions.where((f) => f.owner != null).length} methods.',
    )
    ..writeln()
    ..writeln(_alphabetNav(functions.map((f) => _letter(f.name))))
    ..writeln();
  String? letter;
  for (final function in functions) {
    final current = _letter(function.name);
    if (current != letter) {
      letter = current;
      buffer
        ..writeln()
        ..writeln('## ${_anchorTitle(current)}')
        ..writeln()
        ..writeln(
          '| Function | Declared in | Source | Async | Signature | '
          'Summary |',
        )
        ..writeln('|---|---|---|---|---|---|');
    }
    final owner = function.owner == null
        ? 'top level'
        : '`${function.owner}`${function.isStatic ? ' (static)' : ''}';
    final signature = function.signature
        .replaceAll('|', r'\|')
        .replaceAll('`', "'");
    buffer.writeln(
      '| `${function.name}` | $owner | '
      '${_sourceLink(function.source.path, function.line)} | '
      '${function.isAsync ? 'yes' : ''} | `$signature` | '
      '${function.summary} |',
    );
  }
  return buffer.toString();
}

String _fileReference(
  List<_Source> lib,
  Map<String, List<String>> importers,
  List<_Source> tests,
) {
  final buffer = StringBuffer()
    ..writeln('# File reference')
    ..writeln()
    ..writeln(_generatedNote)
    ..writeln()
    ..writeln(
      'Every Dart file in `lib/`, sorted by path. For each: its purpose '
      '(the file\'s leading comment, else its first documented '
      'declaration), what it declares, the project files it imports, the '
      'files that import it, the tests that import it directly, its '
      'platform, and the platform checks it makes. **Imported by** is the '
      'direct blast radius of a change; follow it before editing. '
      'Platforms: *Windows* (`lib/src/desktop/`, `desktop_*`, `windows_*`), '
      '*Android TV* (the `tv` folders, `tv_*`; the same code serves Google '
      'TV), *Android* (`android_*`), *Shared* (everything else, which may '
      'still branch: see **Branches on**).',
    )
    ..writeln()
    ..writeln('## Index')
    ..writeln()
    ..writeln('| File | Platform | Lines | Purpose |')
    ..writeln('|---|---|---|---|');
  for (final source in lib) {
    buffer.writeln(
      '| [`${source.path}`](#${_fileAnchor(source.path)}) | '
      '${_platform(source.path)} | ${source.lines.length} | '
      '${source.summary} |',
    );
  }
  for (final source in lib) {
    final types = [...source.types]..sort((a, b) => _compare(a.name, b.name));
    final functions = source.functions.where((f) => f.owner == null).toList()
      ..sort((a, b) => _compare(a.name, b.name));
    final users = importers[source.path] ?? const [];
    final libUsers = users.where((path) => path.startsWith('lib/')).toList();
    final testUsers = users.where((path) => !path.startsWith('lib/')).toList();
    final branches = _branches(source);
    buffer
      ..writeln()
      ..writeln('## ${source.path}')
      ..writeln()
      ..writeln(
        '**Source:** ${_fileLink(source.path)} · '
        '**Platform:** ${_platform(source.path)} · '
        '**Lines:** ${source.lines.length}'
        '${branches.isEmpty ? '' : ' · **Branches on:** $branches'}',
      )
      ..writeln()
      ..writeln(
        '**Purpose:** ${source.summary.isEmpty ? '_No leading '
                  'comment; see its declarations._' : source.summary}',
      )
      ..writeln();
    if (types.isNotEmpty) {
      buffer.writeln(
        '**Declares:** ${[for (final type in types) '`${type.name}` (${_role(type)})'].join(', ')}',
      );
      buffer.writeln();
    }
    if (functions.isNotEmpty) {
      buffer.writeln(
        '**Top-level functions:** ${[for (final function in functions) '`${function.name}`'].join(', ')}',
      );
      buffer.writeln();
    }
    final imports = source.imports.toList()..sort();
    buffer
      ..writeln(
        '**Imports (project):** ${imports.isEmpty ? 'none' : [for (final path in imports) '`${path.replaceFirst('lib/', '')}`'].join(', ')}',
      )
      ..writeln();
    final packages = source.packages.toList()..sort();
    if (packages.isNotEmpty) {
      buffer
        ..writeln('**Packages:** ${packages.map((p) => '`$p`').join(', ')}')
        ..writeln();
    }
    buffer
      ..writeln(
        '**Imported by:** ${libUsers.isEmpty ? 'no lib file' : [for (final path in libUsers) '`${path.replaceFirst('lib/', '')}`'].join(', ')}',
      )
      ..writeln()
      ..writeln(
        '**Tests importing it:** ${testUsers.isEmpty ? 'none '
                  'directly (it may be covered through the files that import it)' : [for (final path in testUsers) '`$path`'].join(', ')}',
      );
  }
  return buffer.toString();
}

String _dependencyMap(
  List<_Source> lib,
  Map<String, List<String>> importers,
  Map<String, _Source> byPath,
) {
  String folder(String path) {
    final parts = path.split('/');
    if (parts.length <= 2) return parts.join('/');
    if (parts[1] != 'src') return 'lib';
    // lib/src/<area>[/<sub>]/file.dart
    return parts.length > 4
        ? 'lib/src/${parts[2]}/${parts[3]}'
        : 'lib/src/${parts[2]}';
  }

  final folders = <String>{
    for (final source in lib) folder(source.path),
  }.toList()..sort();
  final edges = <String, Map<String, int>>{};
  for (final source in lib) {
    for (final target in source.imports) {
      if (!target.startsWith('lib/')) continue;
      final from = folder(source.path), to = folder(target);
      if (from == to) continue;
      edges.putIfAbsent(from, () => {});
      edges[from]![to] = (edges[from]![to] ?? 0) + 1;
    }
  }
  String short(String path) => path
      .replaceFirst('lib/src/', '')
      .replaceFirst(RegExp('^lib\$'), 'lib (entry)');
  String node(String path) =>
      short(path).replaceAll(RegExp('[^A-Za-z0-9]'), '_');

  final buffer = StringBuffer()
    ..writeln('# Dependency map')
    ..writeln()
    ..writeln(_generatedNote)
    ..writeln()
    ..writeln(
      'How the folders of `lib/` import each other, which files the most '
      'code depends on, and where each third-party package is used. Counts '
      'are import statements between files, from the source.',
    )
    ..writeln()
    ..writeln('## Folder dependencies')
    ..writeln()
    ..writeln(
      'An arrow `A --> B` means files in A import files in B; the label is '
      'how many imports. Read it to see which layers know about which: '
      'for example, nothing in `models` or `services` should import a UI '
      'folder.',
    )
    ..writeln()
    ..writeln('```mermaid')
    ..writeln('graph LR');
  for (final from in folders) {
    final targets = edges[from];
    if (targets == null) continue;
    for (final to in targets.keys.toList()..sort()) {
      buffer.writeln(
        '  ${node(from)}["${short(from)}"] -->|${targets[to]}| '
        '${node(to)}["${short(to)}"]',
      );
    }
  }
  buffer
    ..writeln('```')
    ..writeln()
    ..writeln('| From folder | Imports from (count) |')
    ..writeln('|---|---|');
  for (final from in folders) {
    final targets = edges[from];
    buffer.writeln(
      '| `${short(from)}` | ${targets == null ? 'nothing outside itself' : [for (final to in targets.keys.toList()..sort()) '`${short(to)}` (${targets[to]})'].join(', ')} |',
    );
  }

  final ranked =
      [
        for (final source in lib)
          (
            path: source.path,
            count: (importers[source.path] ?? const [])
                .where((path) => path.startsWith('lib/'))
                .length,
            tests: (importers[source.path] ?? const [])
                .where((path) => !path.startsWith('lib/'))
                .length,
          ),
      ]..sort((a, b) {
        final order = b.count.compareTo(a.count);
        return order != 0 ? order : a.path.compareTo(b.path);
      });
  buffer
    ..writeln()
    ..writeln('## Most depended-on files')
    ..writeln()
    ..writeln(
      'The files imported by the most other `lib/` files. A change to one '
      'of these reaches widely; run the full test suite and check each '
      'platform.',
    )
    ..writeln()
    ..writeln('| File | Imported by (lib files) | Imported by (tests) |')
    ..writeln('|---|---|---|');
  for (final entry in ranked.take(25)) {
    buffer.writeln(
      '| ${_fileLink(entry.path)} | ${entry.count} | ${entry.tests} |',
    );
  }

  final packages = <String, List<String>>{};
  for (final source in lib) {
    for (final package in source.packages) {
      packages.putIfAbsent(package, () => []).add(source.path);
    }
  }
  final names = packages.keys.toList()..sort(_compare);
  buffer
    ..writeln()
    ..writeln('## Package usage')
    ..writeln()
    ..writeln(
      'Each third-party package imported by `lib/`, A–Z, with the files that '
      'import it. Why each exists is in '
      '[third-party dependencies](../reference/third-party-dependencies.md).',
    )
    ..writeln()
    ..writeln('| Package | Imported by |')
    ..writeln('|---|---|');
  for (final name in names) {
    final users = packages[name]!..sort();
    buffer.writeln(
      '| `$name` | ${users.length > 12 ? '${users.length} files, including '
                '${users.take(6).map((p) => '`${p.replaceFirst('lib/', '')}`').join(', ')}' : users.map((p) => '`${p.replaceFirst('lib/', '')}`').join(', ')} |',
    );
  }
  return buffer.toString();
}

