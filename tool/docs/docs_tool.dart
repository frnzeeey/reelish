/// Where a lib file's code runs, from its folder and name.
String _platform(String path) {
  if (!path.startsWith('lib/')) return 'Test';
  if (path.startsWith('lib/src/desktop/')) return 'Windows';
  if (path.startsWith('lib/src/screens/tv/') ||
      path.startsWith('lib/src/widgets/tv/')) {
    return 'Android TV';
  }
  final name = path.split('/').last;
  if (name.startsWith('desktop_') || name.startsWith('windows_')) {
    return 'Windows';
  }
  if (name.startsWith('android_')) return 'Android';
  return 'Shared';
}

/// The platform checks a shared file makes, so readers know it branches.
String _branches(_Source source) {
  final text = source.text;
  return [
    if (text.contains('DeviceCapabilities.isTv')) 'isTv',
    if (text.contains('DeviceCapabilities.isDesktop')) 'isDesktop',
    if (text.contains('usesTvLayout')) 'usesTvLayout',
    if (text.contains('Platform.isWindows')) 'Platform.isWindows',
    if (text.contains('Platform.isAndroid')) 'Platform.isAndroid',
    if (text.contains('TargetPlatform.windows')) 'TargetPlatform.windows',
    if (text.contains('TargetPlatform.android')) 'TargetPlatform.android',
    if (text.contains('isDesktopPlatform')) 'isDesktopPlatform',
    if (text.contains('TorrentSupport')) 'TorrentSupport',
  ].join(', ');
}

String _role(_Type type) {
  final header = type.header;
  if (type.kind.endsWith('enum')) return 'Enum';
  if (type.kind.endsWith('extension')) return 'Extension';
  if (type.kind.endsWith('mixin')) return 'Mixin';
  if (type.kind.endsWith('typedef')) return 'Typedef';
  if (RegExp(
    r'extends (StatelessWidget|StatefulWidget|InheritedWidget|'
    r'InheritedNotifier|SingleChildRenderObjectWidget|'
    r'LeafRenderObjectWidget|ImplicitlyAnimatedWidget|'
    r'AnimatedWidget|PreferredSizeWidget)',
  ).hasMatch(header)) {
    return 'Widget';
  }
  if (RegExp(r'extends (\w+)?State<').hasMatch(header)) return 'Widget state';
  if (header.contains('extends CustomPainter')) return 'Painter';
  if (header.contains('extends PageRoute') ||
      header.contains('Route<') && header.contains('extends')) {
    return 'Route';
  }
  if (RegExp(r'implements .*Exception').hasMatch(header) ||
      header.contains('extends StateError')) {
    return 'Exception';
  }
  if (header.contains('ChangeNotifier') ||
      header.contains('ValueNotifier') ||
      header.contains('extends Listenable')) {
    return type.source.path.startsWith('lib/src/viewmodels/')
        ? 'View model'
        : 'Notifier / controller';
  }
  final path = type.source.path;
  if (path.startsWith('lib/src/models/')) return 'Model';
  if (path.startsWith('lib/src/services/')) return 'Service type';
  if (path.startsWith('lib/src/theme/')) return 'Theme';
  if (path.startsWith('lib/src/platform/')) return 'Platform adapter';
  return 'Class';
}

String _relations(_Type type) {
  final header = type.header;
  final parts = <String>[];
  for (final keyword in ['extends', 'with', 'implements', 'on']) {
    final match = RegExp(
      '\\b$keyword\\s+(.+?)(?=\\s+(?:extends|with|implements|on)\\b|\$)',
    ).firstMatch(header);
    if (match != null && !(keyword == 'on' && type.kind != 'extension')) {
      parts.add('$keyword ${match.group(1)!.trim()}');
    }
  }
  if (type.kind.endsWith('typedef')) {
    return header.contains('=') ? '= ${header.split('=').last.trim()}' : '';
  }
  return parts.join('; ').replaceAll('|', r'\|');
}

