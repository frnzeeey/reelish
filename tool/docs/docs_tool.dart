// Checking hand-written and generated Markdown

final _linkPattern = RegExp(r'\]\(([^)\s]+)\)');
final _codePattern = RegExp(r'`([^`\s]+)`');

List<String> _checkMarkdown(Directory root) {
  final problems = <String>[];
  final files = <File>[
    File('${root.path}/README.md'),
    File('${root.path}/CONTRIBUTING.md'),
    ...Directory('${root.path}/docs')
        .listSync(recursive: true)
        .whereType<File>()
        .where((file) => file.path.endsWith('.md')),
  ].where((file) => file.existsSync());
  final indexed = File('${root.path}/docs/README.md').existsSync()
      ? File('${root.path}/docs/README.md').readAsStringSync()
      : '';
  for (final file in files) {
    final relative = file.path
        .substring(root.path.length + 1)
        .replaceAll(r'\', '/');
    final text = file.readAsStringSync();
    // Audit records describe the code as it was; their file paths are not
    // kept current, so only their links are checked.
    final historical = text.contains('<!-- docs-check: historical -->');
    final inFence = _fencedLines(text);
    final lines = text.split('\n');
    for (var n = 0; n < lines.length; n++) {
      if (inFence.contains(n)) continue;
      final line = lines[n];
      for (final match in _linkPattern.allMatches(line)) {
        var target = match.group(1)!;
        if (target.startsWith('http') ||
            target.startsWith('mailto:') ||
            target.startsWith('#')) {
          continue;
        }
        target = target.split('#').first;
        final resolved = _resolve(relative, target);
        if (!File('${root.path}/$resolved').existsSync() &&
            !Directory('${root.path}/$resolved').existsSync()) {
          problems.add('$relative:${n + 1}: broken link $target');
        }
      }
      for (final match
          in historical
              ? const <RegExpMatch>[]
              : _codePattern.allMatches(line)) {
        var path = match.group(1)!;
        if (!_checkedRoots.any(path.startsWith)) continue;
        // Patterns and placeholders, not paths.
        if (path.contains('*') ||
            path.contains('<') ||
            path.contains('{') ||
            path.contains('…')) {
          continue;
        }
        path = path.split(':').first.split('#').first;
        if (path.endsWith('.local.dart')) continue;
        if (!File('${root.path}/$path').existsSync() &&
            !Directory('${root.path}/$path').existsSync()) {
          problems.add('$relative:${n + 1}: missing path $path');
        }
      }
    }
    // Every page under docs/ must be reachable from the index.
    if (relative.startsWith('docs/') &&
        relative != 'docs/README.md' &&
        !indexed.contains(relative.substring('docs/'.length))) {
      problems.add('$relative is not linked from docs/README.md');
    }
  }
  return problems;
}

/// Line numbers inside ``` fences, which hold examples, not links.
Set<int> _fencedLines(String text) {
  final lines = text.split('\n');
  final fenced = <int>{};
  var open = false;
  for (var n = 0; n < lines.length; n++) {
    if (lines[n].trimLeft().startsWith('```')) {
      open = !open;
      fenced.add(n);
    } else if (open) {
      fenced.add(n);
    }
  }
  return fenced;
}
