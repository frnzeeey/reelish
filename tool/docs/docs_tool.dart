// Builds and checks Reelish's code reference documentation.
//
//   dart run tool/docs/docs_tool.dart generate   # rewrite docs/codebase/*
//   dart run tool/docs/docs_tool.dart check      # verify links, paths, freshness
//
// The reference pages (files, classes, functions, dependencies) are generated
// from the source so they cannot drift from it: every name, path, signature
// and line number below comes from reading `lib/`, and every summary is the
// first sentence of the symbol's own `///` doc comment. Hand-written guides
// live next to them and link to them.
//
// Parsing is line-based and relies on `dart format` layout (top-level
// declarations at column 0, class members at two spaces), which the repository
// enforces. It uses only the Dart SDK.
import 'dart:io';

const _generatedNote =
    '<!-- Generated by tool/docs/docs_tool.dart from the source. Do not edit by '
    'hand: run `dart run tool/docs/docs_tool.dart generate`. -->';

/// Top-level folders a backticked path may start with; such paths must exist.
const _checkedRoots = [
  '.claude/',
  '.github/',
  'android/',
  'assets/',
  'docs/',
  'integration_test/',
  'lib/',
  'packages/',
  'test/',
  'test_driver/',
  'third_party/',
  'tool/',
  'windows/',
];

/// Dart methods that are lifecycle or framework plumbing, not behaviour worth
/// indexing when undocumented.
const _plumbing = {
  'build',
  'createState',
  'debugFillProperties',
  'didChangeDependencies',
  'didUpdateWidget',
  'dispose',
  'initState',
  'paint',
  'shouldRepaint',
  'toString',
};

void main(List<String> args) {
  final command = args.isEmpty ? 'generate' : args.first;
  final root = _repositoryRoot();
  final sources = _readSources(root);
  final pages = _render(sources, root);
  switch (command) {
    case 'generate':
      for (final MapEntry(:key, :value) in pages.entries) {
        final file = File('${root.path}/$key');
        file.parent.createSync(recursive: true);
        file.writeAsStringSync(value);
        stdout.writeln('wrote $key');
      }
    case 'check':
      final problems = <String>[
        for (final MapEntry(:key, :value) in pages.entries)
          if (!File('${root.path}/$key').existsSync())
            '$key is missing: run the generate command'
          else if (_normalise(File('${root.path}/$key').readAsStringSync()) !=
              _normalise(value))
            '$key is out of date: run the generate command',
        ..._checkMarkdown(root),
        // A new file needs a purpose: a leading comment, a doc comment on
        // the type it is named after, or an entry in _curatedPurposes.
        for (final source in sources)
          if (!source.isTest && source.summary.isEmpty)
            '${source.path} has no purpose: add a leading comment or a '
                '_curatedPurposes entry in tool/docs/docs_tool.dart',
        for (final path in _curatedPurposes.keys)
          if (!sources.any((source) => source.path == path))
            '_curatedPurposes lists $path, which no longer exists',
      ];
      if (problems.isEmpty) {
        stdout.writeln('docs: all checks passed');
      } else {
        problems.forEach(stderr.writeln);
        stderr.writeln('docs: ${problems.length} problem(s)');
        exitCode = 1;
      }
    default:
      stderr.writeln('usage: docs_tool.dart generate|check');
      exitCode = 64;
  }
}

String _normalise(String text) => text.replaceAll('\r\n', '\n');

Directory _repositoryRoot() {
  var dir = File.fromUri(Platform.script).parent;
  while (!File('${dir.path}/pubspec.yaml').existsSync()) {
    final parent = dir.parent;
    if (parent.path == dir.path) {
      throw StateError('pubspec.yaml not found above ${Platform.script}');
    }
    dir = parent;
  }
  return dir;
}

// ---------------------------------------------------------------------------
// Model

class _Source {
  _Source(this.path, this.lines);

  /// Repository-relative, with forward slashes.
  final String path;
  final List<String> lines;
  final imports = <String>{}; // repository paths of local imports
  final packages = <String>{}; // third-party package names
  final types = <_Type>[];
  final functions = <_Function>[];
  String summary = '';

  String get text => lines.join('\n');
  bool get isTest => !path.startsWith('lib/');
}

class _Type {
  _Type({
    required this.name,
    required this.kind,
    required this.line,
    required this.header,
    required this.summary,
  });

  final String name;
  final String kind; // class, abstract class, enum, mixin, extension, typedef
  final int line; // 1-based
  final String header; // declaration up to `{`
  final String summary;
  late final _Source source;

  bool get isPrivate => name.startsWith('_') || name.startsWith('(');
}

class _Function {
  _Function({
    required this.name,
    required this.owner,
    required this.line,
    required this.signature,
    required this.summary,
    required this.isAsync,
    required this.isStatic,
  });

  final String name;
  final String? owner; // declaring type, or null for top-level
  final int line;
  final String signature;
  final String summary;
  final bool isAsync;
  final bool isStatic;
  late final _Source source;
}

// ---------------------------------------------------------------------------
// Parsing

List<_Source> _readSources(Directory root) {
  final sources = <_Source>[];
  for (final folder in ['lib', 'test', 'integration_test']) {
    final dir = Directory('${root.path}/$folder');
    if (!dir.existsSync()) continue;
    for (final entity in dir.listSync(recursive: true)) {
      if (entity is! File || !entity.path.endsWith('.dart')) continue;
      final path = entity.path
          .substring(root.path.length + 1)
          .replaceAll(r'\', '/');
      // The TMDB key file is local and secret; never read or list it.
      if (path.endsWith('.local.dart')) continue;
      sources.add(_Source(path, entity.readAsLinesSync()));
    }
  }
  sources.sort((a, b) => a.path.compareTo(b.path));
  for (final source in sources) {
    _parse(source);
  }
  return sources;
}

final _importPattern = RegExp(r'''^(?:import|export)\s+'([^']+)'(.*);''');
final _typePattern = RegExp(
  r'^((?:abstract |final |sealed |base |interface |mixin )*)'
  r'(class|enum|mixin|extension|typedef)\s+(\w+)?',
);
final _skipStart = RegExp(
  r'^(?:return|if|for|while|switch|case|final|var|late|const|static final|'
  r'static const|throw|await|yield|assert|else|try|catch|super|this|new|'
  r'import|export|part|library|typedef|class|enum|mixin|extension|abstract|'
  r'sealed|base|interface|factory|operator|external\s+factory)\b',
);
final _functionStart = RegExp(
  r'^(?:(static|external)\s+)*'
  r'((?:[\w$.]+(?:<.*>)?\??\s+)+?)?'
  r'([a-zA-Z_$][\w$]*)\s*(<[^()]*>)?\s*\(',
);

void _parse(_Source source) {
  final lines = source.lines;
  for (final line in lines) {
    final match = _importPattern.firstMatch(line);
    if (match == null) continue;
    final target = match.group(1)!;
    if (target.startsWith('package:onfeed/')) {
      source.imports.add('lib/${target.substring('package:onfeed/'.length)}');
    } else if (target.startsWith('package:')) {
      source.packages.add(target.substring(8).split('/').first);
    } else if (!target.startsWith('dart:')) {
      source.imports.add(_resolve(source.path, target));
    }
  }

  String? owner;
  for (var i = 0; i < lines.length; i++) {
    final line = lines[i];
    if (line.startsWith('}')) {
      owner = null;
      continue;
    }
    final type = _typePattern.firstMatch(line);
    if (type != null) {
      final keyword = type.group(2)!;
      var name = type.group(3) ?? '';
      if (keyword == 'extension' && (name == 'on' || name.isEmpty)) {
        final on = RegExp(r'extension\s+on\s+([\w<>?, ]+)').firstMatch(line);
        name = '(extension on ${on?.group(1)?.trim() ?? '?'})';
      }
      final header = _collect(
        lines,
        i,
        (text) => text.contains('{') || text.trimRight().endsWith(';'),
      );
      final declared = _Type(
        name: name,
        kind: '${type.group(1)!.trim()} $keyword'.trim(),
        line: i + 1,
        header: header.split('{').first.trim(),
        summary: _docSummary(lines, i),
      )..source = source;
      source.types.add(declared);
      owner = line.trimRight().endsWith(';') ? null : name;
      continue;
    }
    // Top-level functions (column 0) and members (two spaces in a type).
    final String body;
    if (owner == null && !line.startsWith(' ')) {
      body = line;
    } else if (owner != null &&
        line.startsWith('  ') &&
        !line.startsWith('   ')) {
      body = line.substring(2);
    } else {
      continue;
    }
    if (body.isEmpty || body.startsWith('//') || body.startsWith('@')) {
      continue;
    }
    if (_skipStart.hasMatch(body)) continue;
    if (body.startsWith('const ') || body.startsWith('factory ')) continue;
    final function = _functionStart.firstMatch(body);
    if (function == null) continue;
    final name = function.group(3)!;
    if (const {'get', 'set', 'operator'}.contains(name)) continue;
    final returnType = (function.group(2) ?? '').trim();
    if (returnType.endsWith(' get') || returnType.endsWith(' set')) continue;
    // Constructors: `Name(`, `Name.named(`.
    if (owner != null && (name == owner || body.startsWith('$owner.'))) {
      continue;
    }
    // A bare call or expression at column 0 has no return type; only `main`
    // and members may omit it.
    // A long return type that `dart format` wrapped onto the line above.
    var declaration = i;
    var wrappedType = '';
    if (returnType.isEmpty && i > 0) {
      final above = lines[i - 1];
      final indent = owner == null ? '' : '  ';
      final type = above.trim();
      if (above.startsWith(indent) &&
          !above.startsWith('$indent ') &&
          RegExp(r'^[\w$.]+(<.*>)?\??$').hasMatch(type) &&
          !_skipStart.hasMatch(type)) {
        declaration = i - 1;
        wrappedType = '$type ';
      }
    }
    if (returnType.isEmpty &&
        wrappedType.isEmpty &&
        owner == null &&
        name != 'main') {
      continue;
    }
    final collected = _collectSignature(lines, i);
    if (collected == null) continue;
    final signature = (
      text: '$wrappedType${collected.text}',
      isAsync:
          collected.isAsync ||
          RegExp(r'^(?:Future|FutureOr|Stream)\b').hasMatch(wrappedType),
    );
    final annotations = _annotations(lines, declaration);
    final summary = _docSummary(lines, declaration);
    final isPrivate = name.startsWith('_');
    // Framework overrides and undocumented private helpers are noise; a
    // documented private method is behaviour worth finding.
    if (annotations.contains('@override') && summary.isEmpty) continue;
    if (_plumbing.contains(name) && summary.isEmpty) continue;
    if (isPrivate && summary.isEmpty) continue;
    source.functions.add(
      _Function(
        name: name,
        owner: owner,
        line: i + 1,
        signature: signature.text,
        summary: summary,
        isAsync: signature.isAsync,
        isStatic: function.group(1) == 'static' || body.startsWith('static '),
      )..source = source,
    );
  }
  source.summary = _fileSummary(source);
}

String _resolve(String from, String relative) {
  final parts = from.split('/')..removeLast();
  for (final part in relative.split('/')) {
    if (part == '..') {
      parts.removeLast();
    } else if (part != '.') {
      parts.add(part);
    }
  }
  return parts.join('/');
}

String _collect(List<String> lines, int start, bool Function(String) done) {
  final buffer = StringBuffer();
  for (var i = start; i < lines.length && i < start + 12; i++) {
    buffer.write('${lines[i].trim()} ');
    if (done(lines[i])) break;
  }
  return buffer.toString().replaceAll(RegExp(r'\s+'), ' ').trim();
}

({String text, bool isAsync})? _collectSignature(List<String> lines, int i) {
  final buffer = StringBuffer();
  var depth = 0;
  var opened = false;
  for (var k = i; k < lines.length && k < i + 40; k++) {
    final line = lines[k];
    for (var c = 0; c < line.length; c++) {
      final char = line[c];
      buffer.write(char);
      if (char == '(') {
        depth++;
        opened = true;
      } else if (char == ')') {
        depth--;
        if (opened && depth == 0) {
          final rest = line.substring(c + 1).trim();
          // A call statement, not a declaration.
          if (rest.startsWith(';') ||
              rest.startsWith(',') ||
              rest.startsWith('.') ||
              rest.startsWith(')')) {
            return null;
          }
          final isAsync = RegExp(r'^(async\*?|sync\*)').hasMatch(rest);
          final modifier = RegExp(r'^(async\*?|sync\*)').firstMatch(rest);
          final text = buffer
              .toString()
              .replaceAll(RegExp(r'\s+'), ' ')
              .replaceAllMapped(RegExp(r',\s*([)}\]])'), (m) => m[1]!)
              .replaceAll('( ', '(')
              .trim();
          return (
            text: modifier == null ? text : '$text ${modifier.group(0)}',
            // Declared `async`, or returns a Future or Stream (not a type
            // that merely starts with those words, like StreamDiscovery).
            isAsync:
                isAsync ||
                RegExp(
                  r'^(?:(?:static|external)\s+)*(?:Future|FutureOr|Stream)\b',
                ).hasMatch(text),
          );
        }
      }
    }
    buffer.write(' ');
  }
  return null;
}

List<String> _annotations(List<String> lines, int i) {
  final found = <String>[];
  for (var k = i - 1; k >= 0; k--) {
    final line = lines[k].trim();
    if (line.startsWith('@')) {
      found.add(line);
    } else {
      break;
    }
  }
  return found;
}

/// The first sentence of the `///` comment above line [i], annotations
/// skipped; '' when there is none.
String _docSummary(List<String> lines, int i) {
  var k = i - 1;
  while (k >= 0 && lines[k].trim().startsWith('@')) {
    k--;
  }
  final doc = <String>[];
  while (k >= 0 && lines[k].trim().startsWith('///')) {
    doc.insert(0, lines[k].trim().substring(3).trim());
    k--;
  }
  return _firstSentence(doc);
}

String _firstSentence(List<String> doc) {
  final paragraph = <String>[];
  for (final line in doc) {
    if (line.isEmpty) break;
    if (line.startsWith('```') || line.startsWith('*') && paragraph.isEmpty) {
      break;
    }
    paragraph.add(line);
  }
  final text = paragraph.join(' ').replaceAll(RegExp(r'\s+'), ' ').trim();
  final end = RegExp(r'[.!?](\s|$)').firstMatch(text);
  final sentence = end == null ? text : text.substring(0, end.start + 1);
  return sentence
      .replaceAllMapped(RegExp(r'\[([^\]]+)\]'), (m) => '`${m[1]}`')
      .replaceAll('|', r'\|');
}

/// A file's purpose: its leading `//` comment, else the doc comment of its
/// first public type or function, else of its first declaration.
String _fileSummary(_Source source) {
  final header = <String>[];
  for (final line in source.lines) {
    final trimmed = line.trim();
    if (trimmed.startsWith('// ignore') || trimmed.startsWith('// coverage')) {
      continue;
    }
    if (trimmed.startsWith('//') && !trimmed.startsWith('///')) {
      header.add(trimmed.substring(2).trim());
    } else if (trimmed.startsWith('@TestOn') || trimmed.startsWith('library')) {
      continue;
    } else {
      break;
    }
  }
  if (header.isNotEmpty) return _firstSentence(header);
  // The type the file is named after (`playback_coordinator.dart` →
  // `PlaybackCoordinator`) speaks for it.
  final named = source.path
      .split('/')
      .last
      .replaceAll('.dart', '')
      .split('_')
      .map(
        (part) => part.isEmpty ? '' : part[0].toUpperCase() + part.substring(1),
      )
      .join();
  for (final type in source.types) {
    if (type.name == named && type.summary.isNotEmpty) return type.summary;
  }
  // Otherwise only an unambiguous source: the file's one public type or
  // one top-level function. A helper's comment would misdescribe the file.
  final public = source.types.where((type) => !type.isPrivate).toList();
  final topLevel = source.functions.where((f) => f.owner == null).toList();
  if (public.length == 1 &&
      public.single.summary.isNotEmpty &&
      (topLevel.isEmpty || public.single.name == named)) {
    return public.single.summary;
  }
  if (public.isEmpty && topLevel.length == 1) return topLevel.single.summary;
  return _curatedPurposes[source.path] ?? '';
}

