// A stroke, or a shape to fill. `cut` removes it from what is already drawn.
const s = (d, w = 2) => ({ d, w });
const f = (d, evenOdd = false) => ({ d, evenOdd });
const circle = (x, y, r) =>
  `M${x - r} ${y}a${r} ${r} 0 1 0 ${r * 2} 0a${r} ${r} 0 1 0 ${-r * 2} 0Z`;
const rect = (x, y, w, h, r) =>
  `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
const c = (x, y, r, w = 2) => s(circle(x, y, r), w);
const d = (x, y, r) => f(circle(x, y, r));
const r = (x, y, w, h, rad, sw = 2) => s(rect(x, y, w, h, rad), sw);
const rf = (x, y, w, h, rad) => f(rect(x, y, w, h, rad));
const cut = (op) => ({ ...op, cut: true });

/** The same stroke cut wider first, so what crosses it stands clear. */
const clear = (path, w = 2, gap = 3.6) => [cut(s(path, w + gap)), s(path, w)];

/**
 * An arc of a true circle, in degrees clockwise from three o'clock, so the
 * circular arrows all share one centre and radius.
 */
const arc = (from, to, cx = 12, cy = 12, radius = 9) => {
  const at = (deg) => {
    const a = (deg * Math.PI) / 180;
    return `${(cx + radius * Math.cos(a)).toFixed(3)} ${(cy + radius * Math.sin(a)).toFixed(3)}`;
  };
  const sweep = to > from ? 1 : 0;
  const large = Math.abs(to - from) > 180 ? 1 : 0;
  return `M${at(from)}A${radius} ${radius} 0 ${large} ${sweep} ${at(to)}`;
};

/** A slash through a drawing, for "off" and "unavailable". */
const off = (...ops) => [...ops.flat(), ...clear('M4 4 20 20')];

/** A rounded triangle pointing right; a stroke gives the soft corners. */
const tri = (x, y, h, w = h * 0.86, sw = 2.4) => {
  const path = `M${x} ${y - h / 2}L${x + w} ${y}L${x} ${y + h / 2}Z`;
  return [f(path), s(path, sw)];
};
const triLeft = (x, y, h, w = h * 0.86, sw = 2.4) => {
  const path = `M${x} ${y - h / 2}L${x - w} ${y}L${x} ${y + h / 2}Z`;
  return [f(path), s(path, sw)];
};

/** A gear: even teeth with soft shoulders. */
function gear(cx, cy, outer, inner, teeth) {
  let path = '';
  for (let i = 0; i < teeth; i++) {
    const step = (Math.PI * 2) / teeth;
    const at = (radius, offset) => {
      const a = i * step + offset * step - Math.PI / 2;
      return `${(cx + radius * Math.cos(a)).toFixed(3)} ${(cy + radius * Math.sin(a)).toFixed(3)}`;
    };
    path += `${i === 0 ? 'M' : 'L'}${at(inner, -0.5)}L${at(inner, -0.3)}L${at(outer, -0.17)}L${at(outer, 0.17)}L${at(inner, 0.3)}`;
  }
  return `${path}Z`;
}

